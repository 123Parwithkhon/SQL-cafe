  typeof v === 'string' && (UNIVERSITIES as readonly string[]).includes(v);

/** Короткое имя вуза для таблиц: всё до « — » или до « (» */
export function shortUniversity(name: string): string {
  return name.split(' — ')[0].split(' (')[0];
}
