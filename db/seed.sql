-- Сумма заказа = Σ quantity × price
UPDATE orders
SET total = (
  SELECT SUM(oi.quantity * t.price)
  FROM order_items AS oi
  JOIN teas AS t ON t.id = oi.tea_id
  WHERE oi.order_id = orders.id
);
